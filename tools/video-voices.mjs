#!/usr/bin/env node
// Simple voice track for the "Make video" button: one HTTP TTS server (Fish Audio Drama 3, /v1/audio/speech), no ssh, no GPU lock.
//   node tools/video-voices.mjs <casters-tts.json> --url http://127.0.0.1:8000 [--out dir] [--casters casters.json] [--voice caster_a=<dir>]
// The studio path (tools/caster-voice.mjs: several takes per line, read-back, noise checks, polish) stays for hand-made videos.
// This one asks for up to 2 takes per line, keeps the first one whose length fits, levels it, places it on the timeline and writes
// the same files render-broadcast.mjs --voices expects: <base>-casters-voice.wav and <base>-casters-voice.json.
// Failure rules: server not reachable or a reference missing -> VoiceError (the caller makes a captions-only video);
// a single line that fails twice is dropped (its caption goes with it); more than 40 percent dropped -> VoiceError.
import '../server/local-env.mjs'; // machine-local RTS_* defaults (local-env.json) before anything reads them
import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { SR, SAMPLING, VOICE_DIRS, placeTakes, cueTimes, wavF32, scriptHash } from './caster-voice.mjs';

export class VoiceError extends Error {}
const clamp = (v, a, b) => Math.max(a, Math.min(b, v));
const redact = (s, key) => (key ? String(s).split(key).join('***') : String(s));

// is a Drama 3 (or compatible) server answering? /health first, then /v1/models
export async function checkTts(url, { timeoutMs = 3000, fetchImpl = fetch } = {}) {
  if (!/^https?:\/\//.test(String(url || ''))) return { ok: false, error: 'no TTS server URL set (Settings > Voices)' };
  const base = String(url).replace(/\/+$/, '');
  let last = 'no answer';
  for (const p of ['/health', '/v1/models']) {
    try {
      const r = await fetchImpl(base + p, { signal: AbortSignal.timeout(timeoutMs) });
      if (r.ok) return { ok: true, url: base };
      last = `HTTP ${r.status} from ${p}`;
    } catch (e) { last = e.name === 'TimeoutError' ? 'timeout' : e.cause?.code || e.message; }
  }
  return { ok: false, error: `TTS server at ${base} is not reachable (${last})` };
}

export function voiceRef(name, overrides = {}) {
  if (!(name in VOICE_DIRS)) throw new VoiceError(`unknown voice "${name}"`);
  const dir = overrides[name] || VOICE_DIRS[name];
  if (!dir) throw new VoiceError(`no voice reference folder set for ${name} (Settings > Voices, or env RTS_VOICES_DIR)`);
  const wav = path.join(dir, 'referenz.wav'), txt = path.join(dir, 'transkript.txt');
  if (!fs.existsSync(wav) || !fs.existsSync(txt)) throw new VoiceError(`voice reference for ${name} not found in ${dir} (needs referenz.wav and transkript.txt; set it in Settings > Voices)`);
  return { name, dir, wav, text: fs.readFileSync(txt, 'utf8').trim() };
}

async function registerVoice(base, serverName, ref, fetchImpl) {
  const fd = new FormData();
  fd.set('name', serverName);
  fd.set('ref_text', ref.text);
  fd.set('consent', 'synthetic voice generated by the model itself from a text description, no real person is imitated');
  fd.set('audio_sample', new Blob([fs.readFileSync(ref.wav)], { type: 'audio/wav' }), 'referenz.wav');
  let r;
  try { r = await fetchImpl(base + '/v1/audio/voices', { method: 'POST', body: fd, signal: AbortSignal.timeout(60000) }); } catch (e) { throw new VoiceError(`TTS server not reachable (${e.cause?.code || e.message})`); }
  if (r.ok) return;
  const t = (await r.text().catch(() => '')).slice(0, 200);
  if (/exist|already|duplicate/i.test(t) || r.status === 409) return; // registered by an earlier video
  throw new VoiceError(`TTS server refused the voice reference for ${ref.name}: HTTP ${r.status} ${t}`);
}

// wav bytes -> mono float32 at 48 kHz, leveled to about -20 LUFS (one pass loudnorm per line)
export function decodeLevel(bytes) {
  const r = spawnSync('ffmpeg', ['-nostdin', '-loglevel', 'error', '-i', 'pipe:0', '-af', 'highpass=f=70,loudnorm=I=-20:TP=-2:LRA=11', '-f', 'f32le', '-ac', '1', '-ar', String(SR), 'pipe:1'], { input: bytes, maxBuffer: 1 << 28 });
  if (r.status !== 0 || !r.stdout.length) throw new Error('could not decode the audio the TTS server returned');
  const b = r.stdout;
  return new Float32Array(b.buffer.slice(b.byteOffset, b.byteOffset + b.byteLength - (b.byteLength % 4)));
}

export async function buildVoices({ manifestFile, castersFile = null, outDir, base = null, url, voiceDirs = {}, log = () => {}, onProgress = () => {}, fetchImpl = fetch, signal = null, takes = 2, key = '' }) {
  const man = JSON.parse(fs.readFileSync(manifestFile, 'utf8'));
  const entries = man.entries;
  if (!entries?.length) throw new VoiceError('the script has no lines to voice');
  const track = castersFile && fs.existsSync(castersFile) ? JSON.parse(fs.readFileSync(castersFile, 'utf8')) : null;
  const baseUrl = String(url).replace(/\/+$/, '');
  base = base || path.basename(manifestFile).replace(/-tts\.json$|\.json$/, '');
  fs.mkdirSync(outDir, { recursive: true });
  const headers = key ? { Authorization: `Bearer ${key}` } : {};
  const fetchK = (u, init = {}) => fetchImpl(u, { ...init, headers: { ...headers, ...(init.headers || {}) } });

  const names = [...new Set(entries.map((e) => e.voice))];
  const refs = Object.fromEntries(names.map((n) => [n, voiceRef(n, voiceDirs)]));
  for (const n of names) await registerVoice(baseUrl, `rts_${n}`, refs[n], fetchK);
  log(`voices registered: ${names.join(', ')}`);

  const lines = [], dropped = [];
  let done = 0;
  for (const e of entries) {
    if (signal?.aborted) throw new VoiceError('cancelled');
    const maxTok = Math.round(clamp(2.5 * (e.expected_s || 3) * 21.5, 150, 700));
    let best = null, err = null;
    for (let k = 0; k < takes && !best; k++) {
      try {
        const r = await fetchK(baseUrl + '/v1/audio/speech', { method: 'POST', headers: { 'Content-Type': 'application/json' }, signal: signal || AbortSignal.timeout(300000),
          body: JSON.stringify({ input: e.text_tts, response_format: 'wav', max_new_tokens: maxTok, voice: `rts_${e.voice}`, ...SAMPLING }) });
        if (!r.ok) { err = `HTTP ${r.status}`; continue; }
        const x = decodeLevel(Buffer.from(await r.arrayBuffer()));
        const dur = x.length / SR, [lo, hi] = e.accept_take_s || [0.1, 60];
        if (dur >= lo * 0.8 && dur <= hi * 1.2) best = { x, dur };
        else err = `take length ${dur.toFixed(1)} s outside ${lo}-${hi} s`;
      } catch (ex) {
        if (signal?.aborted) throw new VoiceError('cancelled');
        err = redact(ex.cause?.code || ex.message, key);
        if (done === 0 && k === 0 && /ECONNREFUSED|ENOTFOUND|fetch failed|ECONNRESET/i.test(String(ex.cause?.code || ex.message))) throw new VoiceError(`TTS server not reachable (${err})`);
      }
    }
    done++; onProgress(done, entries.length);
    if (!best) { dropped.push({ id: e.id, why: err || 'no usable take' }); log(`line ${e.id} dropped: ${err}`); continue; }
    lines.push({ e, x: best.x, dur: best.dur });
  }
  if (dropped.length > 0.4 * entries.length) throw new VoiceError(`the TTS server failed on ${dropped.length} of ${entries.length} lines (${dropped[0].why})`);
  if (!lines.length) throw new VoiceError('no line could be voiced');

  const duration = track?.duration_s ?? Math.max(...entries.map((e) => e.latest_end_s));
  const { placed, changes } = placeTakes(lines.map((l) => ({ id: l.e.id, interject: !!l.e.interject, planned: l.e.start_s, latest_end: l.e.latest_end_s, dur: l.dur })), { duration });
  const pl = new Map(placed.map((p) => [p.id, p]));
  const N = Math.ceil((Math.max(duration, ...placed.map((p) => p.end)) + 1) * SR);
  const mix = new Float32Array(N);
  const outLines = [];
  for (const l of lines) {
    const p = pl.get(l.e.id);
    const x = l.x; // never time-stretched: a long take pushes the next lines (placeTakes)
    const s0 = Math.round(p.start * SR);
    for (let i = 0; i < x.length && s0 + i < N; i++) mix[s0 + i] += x[i];
    const end = +(p.start + x.length / SR).toFixed(3);
    const t0 = track?.lines.find((t) => t.id === l.e.id);
    outLines.push({ id: l.e.id, speaker: l.e.speaker, voice: l.e.voice, delivery: l.e.delivery, text: l.e.text, start: p.start, end, planned_start: p.planned, window_end: p.window_end,
      cues: t0 ? cueTimes(t0.cues, null, { start: p.start, end }) : [] });
  }
  let peak = 0; for (let i = 0; i < N; i++) peak = Math.max(peak, Math.abs(mix[i]));
  if (peak > 0.89) { const g = 0.89 / peak; for (let i = 0; i < N; i++) mix[i] *= g; }
  const wavOut = path.join(outDir, `${base}-casters-voice.wav`);
  const ff = spawnSync('ffmpeg', ['-nostdin', '-y', '-loglevel', 'error', '-i', 'pipe:0', '-c:a', 'pcm_s24le', wavOut], { input: wavF32([mix, mix]), maxBuffer: 1 << 28 });
  if (ff.status !== 0) throw new Error('ffmpeg failed while writing the voice track: ' + String(ff.stderr).slice(0, 300));
  const json = { version: 1, tool: 'tools/video-voices.mjs', created: new Date().toISOString(), manifest: { file: path.basename(manifestFile), script_hash: scriptHash(entries) },
    wav: path.basename(wavOut), sr: SR, channels: 2, duration_s: +(N / SR).toFixed(3), lines: outLines, dropped, changes, failed: [] };
  const jsonOut = path.join(outDir, `${base}-casters-voice.json`);
  fs.writeFileSync(jsonOut, JSON.stringify(json, null, 1));
  return { wav: wavOut, json: jsonOut, lines: outLines.length, dropped };
}

async function main() {
  const A = process.argv.slice(2), opt = (k) => { const i = A.indexOf(k); return i >= 0 ? A[i + 1] : null; };
  const man = A.find((x, i) => !x.startsWith('--') && !(A[i - 1] || '').startsWith('--'));
  if (!man || !opt('--url')) { console.error('usage: node tools/video-voices.mjs <casters-tts.json> --url http://host:8000 [--out dir] [--casters casters.json] [--voice caster_a=<dir>]'); process.exit(2); }
  const voiceDirs = Object.fromEntries(A.flatMap((x, i) => (x === '--voice' ? [A[i + 1].split('=')] : [])));
  const r = await buildVoices({ manifestFile: path.resolve(man), castersFile: opt('--casters'), outDir: path.resolve(opt('--out') || path.dirname(man)), url: opt('--url'), voiceDirs, log: console.log });
  console.log(`${r.lines} lines voiced, ${r.dropped.length} dropped\n${r.wav}\n${r.json}`);
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main().catch((e) => { console.error(e.message); process.exit(1); });
